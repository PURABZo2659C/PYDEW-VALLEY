"""Generate build/version_info.py - the Windows version resource.

PyInstaller deserializes this file with eval(), so it has to be a single
expression built from PyInstaller's own versioninfo classes. Writing it
by hand is error prone (a stray assignment breaks the whole build), so
this script builds the object and serializes it instead.

The version comes from build/VERSION.txt, which is the single place the
version is defined - the ZIP file name and the in-game credits screen
read it from there too.

Run:  python build/make_version_info.py
"""

import os

from PyInstaller.utils.win32.versioninfo import (
    VSVersionInfo, FixedFileInfo, StringFileInfo, StringTable,
    StringStruct, VarFileInfo, VarStruct,
)

BUILD_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(BUILD_DIR)
TARGET = os.path.join(BUILD_DIR, 'version_info.py')
VERSION_FILE = os.path.join(BUILD_DIR, 'VERSION.txt')


def read_version():
    """The version string from VERSION.txt, e.g. '1.0.1'."""
    with open(VERSION_FILE, 'r', encoding='utf-8') as handle:
        return handle.read().strip()


def version_tuple(version):
    """'1.0.1' -> (1, 0, 1, 0) for the four-part Windows version."""
    parts = [int(p) for p in version.split('.') if p.isdigit()]
    while len(parts) < 4:
        parts.append(0)
    return tuple(parts[:4])


def build():
    version = read_version()
    quad = version_tuple(version)
    text_version = '.'.join(str(p) for p in quad)

    fields = [
        ('CompanyName', 'Pydew Valley'),
        ('FileDescription', 'Pydew Valley'),
        ('FileVersion', text_version),
        ('InternalName', 'PydewValley'),
        ('LegalCopyright',
         'Game code and original art by the Pydew Valley team. '
         'Third-party assets are credited in THIRD_PARTY_NOTICES.txt.'),
        ('OriginalFilename', 'PydewValley.exe'),
        ('ProductName', 'Pydew Valley'),
        ('ProductVersion', text_version),
    ]

    info = VSVersionInfo(
        ffi=FixedFileInfo(
            filevers=quad,
            prodvers=quad,
            mask=0x3f,
            flags=0x0,
            OS=0x40004,      # VOS_NT_WINDOWS32
            fileType=0x1,    # VFT_APP
            subtype=0x0,
            date=(0, 0),
        ),
        kids=[
            StringFileInfo([
                StringTable('040904b0', [
                    StringStruct(name, value) for name, value in fields
                ]),
            ]),
            VarFileInfo([
                VarStruct('Translation', [1033, 1200]),
            ]),
        ],
    )

    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, 'w', encoding='utf-8') as handle:
        handle.write('# Generated by build/make_version_info.py - do not edit by hand.\n')
        handle.write(str(info))
        handle.write('\n')
    print('wrote %s (version %s)' % (TARGET, version))

    # Prove PyInstaller can load it back.
    from PyInstaller.utils.win32.versioninfo import load_version_info_from_text_file
    load_version_info_from_text_file(TARGET)
    print('verified: PyInstaller can deserialize it')


if __name__ == '__main__':
    build()
